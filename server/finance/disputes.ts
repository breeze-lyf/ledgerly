// Dispute defense: when PayPal reports a dispute on a milestone capture or invoice, the agent assembles an evidence
// pack (SOW, delivery evidence, the client's written approval, the money trail) as a PDF and a defense card.
// Submitting to PayPal (provide-evidence) stays behind DISPUTE_SUBMIT=1 until it is verified in the sandbox.
import { randomUUID } from "node:crypto";
import { db, object, saveObject } from "../db.js";
import { paypal } from "../paypal/index.js";
import { plans, runners, savePlan, type Plan } from "./plans.js";
import { feLog, project, projects, type Project } from "./store.js";
import { learn } from "./memory.js";

// Evidence type by dispute reason (PayPal Disputes API). The dispute's own requested type wins when present.
const TYPE: Record<string, string> = { MERCHANDISE_OR_SERVICE_NOT_RECEIVED: "PROOF_OF_FULFILLMENT", MERCHANDISE_OR_SERVICE_NOT_AS_DESCRIBED: "OTHER", UNAUTHORISED: "OTHER", DUPLICATE_TRANSACTION: "OTHER" };
export const submissionEnabled = () => process.env.DISPUTE_SUBMIT === "1";

function findCapture(captureId: string): { proj: Project; milestone_id?: string } | undefined {
  for (const p of projects()) { const c = p.hold?.captures?.find((x: any) => x.id === captureId); if (c) return { proj: p, milestone_id: c.milestone_id }; }
  for (const pl of plans()) {
    const inv = pl.steps.find(s => s.type === "invoice")?.result?.invoice_id;
    if (inv && (db.prepare("SELECT 1 FROM settlements WHERE invoice_id=? AND capture_id=?").get(inv, captureId))) return { proj: project(pl.project_id)!, milestone_id: pl.milestone_id };
  }
}

export function pdf(lines: string[]) {
  const esc = (s: string) => s.replace(/[^\x20-\x7e]/g, "?").replace(/([()\\])/g, "\\$1");
  const pages: string[][] = []; for (let i = 0; i < lines.length; i += 48) pages.push(lines.slice(i, i + 48));
  const objs: string[] = ["<</Type/Catalog/Pages 2 0 R>>", "", "<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>"];
  const kids: number[] = [];
  for (const pg of pages) {
    const stream = "BT /F1 10 Tf 50 790 Td 14 TL " + pg.map(l => `(${esc(l.slice(0, 100))}) '`).join(" ") + " ET";
    objs.push(`<</Length ${stream.length}>>stream\n${stream}\nendstream`);
    objs.push(`<</Type/Page/Parent 2 0 R/MediaBox[0 0 612 842]/Contents ${objs.length} 0 R/Resources<</Font<</F1 3 0 R>>>>>>`);
    kids.push(objs.length);
  }
  objs[1] = `<</Type/Pages/Kids[${kids.map(k => k + " 0 R").join(" ")}]/Count ${kids.length}>>`;
  let out = "%PDF-1.4\n"; const offs: number[] = [];
  objs.forEach((o, i) => { offs.push(out.length); out += `${i + 1} 0 obj${o}endobj\n`; });
  const x = out.length;
  out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offs.map(o => String(o).padStart(10, "0") + " 00000 n \n").join("") + `trailer<</Size ${objs.length + 1}/Root 1 0 R>>\nstartxref\n${x}\n%%EOF\n`;
  return Buffer.from(out, "latin1");
}

export function buildDefense(dispute: any, proj: Project, milestoneId?: string) {
  const related = plans().filter(p => p.project_id === proj.id && p.kind !== "dispute" && (!milestoneId || p.milestone_id === milestoneId));
  const evidence = related.flatMap(p => p.evidence).sort((a, b) => a.at.localeCompare(b.at));
  const money = related.flatMap(p => p.steps.filter(s => s.status === "done" && (s.type === "capture_hold" || s.type === "invoice")).map(s => `${s.type === "capture_hold" ? "Captured" : "Invoiced"} ${s.amount?.toFixed(2)} ${proj.currency} for milestone ${p.milestone_id} after approval (${p.updated_at.slice(0, 10)})`));
  const m = proj.milestones.find(x => x.id === milestoneId);
  const lines = [
    "LEDGERLY EVIDENCE PACK", `Dispute ${dispute.dispute_id} · reason ${dispute.reason} · ${dispute.dispute_amount?.value} ${dispute.dispute_amount?.currency_code}`, "",
    `Project: ${proj.title}   Client: ${proj.client} <${proj.client_email}>`, m ? `Milestone: ${m.title} (${m.amount.toFixed(2)} ${proj.currency}) — acceptance criteria: ${m.criteria || "n/a"}` : "", "",
    "1. Agreed scope (SOW excerpt)", ...wrap(proj.sow || "(no SOW text on file)", 95).slice(0, 8), "",
    "2. Delivery and client acceptance timeline", ...evidence.flatMap(e => [`- ${e.at.slice(0, 16).replace("T", " ")} UTC · ${e.source === "github" ? "GitHub" : "Email from " + e.actor}: ${e.title}`, ...(e.excerpt ? wrap(`  "${e.excerpt}"`, 95).slice(0, 3) : []), ...(e.url ? [`  ${e.url}`] : [])]), "",
    "3. Payment trail", ...(money.length ? money.map(x => "- " + x) : ["- (none recorded)"]), "",
    "4. Summary", ...wrap(`The work was delivered as recorded above and the client accepted it in writing before any funds were captured. Funds were captured only after that acceptance, against a PayPal authorization the client approved.`, 95),
    "", `Generated by Ledgerly from recorded events on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC.`];
  return { lines: lines.filter(l => l !== undefined), evidence, money };
}
const wrap = (s: string, n: number) => s.replace(/\s+/g, " ").match(new RegExp(`.{1,${n}}(\\s|$)`, "g"))?.map(x => x.trim()) || [s];

export async function onDispute(e: any) {
  const r = e.resource || {};
  const id = r.dispute_id || r.id;
  if (!id) return false;
  const capIds = (r.disputed_transactions || []).map((t: any) => t.seller_transaction_id).filter(Boolean);
  const hit = capIds.map(findCapture).find(Boolean);
  const existing = object("fe-dispute:" + id);
  if (!hit) return false;
  saveObject({ id: "fe-dispute:" + id, dispute_id: id, project_id: hit.proj.id, milestone_id: hit.milestone_id, domain: hit.proj.client_email.split("@")[1], status: r.status, reason: r.reason, amount: r.dispute_amount, last_event: e.event_type, plan_id: existing?.plan_id });
  if (existing) { feLog(hit.proj.id, "dispute", `Dispute ${id}: ${e.event_type.replace("CUSTOMER.DISPUTE.", "").toLowerCase()} (${r.status || ""})`); return true; }
  const d = buildDefense({ ...r, dispute_id: id }, hit.proj, hit.milestone_id);
  saveObject({ id: "fe-dispute-pdf:" + id, b64: pdf(d.lines).toString("base64") });
  const evidenceType = r.evidences?.find((x: any) => x.source === "REQUESTED_FROM_SELLER")?.evidence_type || TYPE[r.reason] || "OTHER";
  const plan: Plan = savePlan({ id: "plan_" + randomUUID().slice(0, 8), project_id: hit.proj.id, milestone_id: "dispute:" + id, kind: "dispute", status: "pending",
    headline: `Dispute opened on ${hit.proj.title}: defense ready`, detection: { milestone_id: hit.milestone_id || "", delivery: [], approval: [], confidence: d.evidence.length ? 0.9 : 0.4, method: "rules",
      rationale: d.evidence.length ? `${d.evidence.length} timestamped records show delivery and the client's written acceptance before capture.` : "No delivery evidence on file for this capture; consider accepting the claim." },
    evidence: d.evidence, dispute: { id, reason: r.reason, amount: r.dispute_amount, evidence_type: evidenceType },
    steps: [{ id: "d1", type: "evidence_pack", label: `Evidence pack PDF built (${d.lines.length} lines, ${d.evidence.length} records)`, status: "done", result: { pdf: `finance/disputes/${id}/evidence.pdf` } },
      { id: "d2", type: "submit_evidence", label: submissionEnabled() ? `Submit to PayPal as ${evidenceType}` : `Submit to PayPal as ${evidenceType} (submission off until verified in sandbox)`, status: "pending" }],
    created_at: new Date().toISOString(), updated_at: new Date().toISOString() } as any);
  saveObject({ ...object("fe-dispute:" + id), plan_id: plan.id });
  feLog(hit.proj.id, "dispute", `Dispute ${id} (${r.reason}) on ${hit.proj.title}. I assembled the evidence pack in seconds; approve to file it.`, { plan_id: plan.id });
  learn(hit.proj.client_email);
  return true;
}

runners.submit_evidence = async (_s, p) => {
  const d = (p as any).dispute;
  if (!submissionEnabled()) return { status: "skipped", result: { reason: "DISPUTE_SUBMIT is off; download the PDF and upload it in the PayPal Resolution Center" } };
  const file = Buffer.from(object("fe-dispute-pdf:" + d.id).b64, "base64");
  const r = await paypal.provideDisputeEvidence(d.id, { evidences: [{ evidence_type: d.evidence_type, notes: "Delivery and written client acceptance before capture; see attached Ledgerly evidence pack." }] }, file, "ledgerly-evidence.pdf");
  return { status: "done", result: { submitted: true, links: (r.links || []).map((l: any) => l.rel) } };
};
